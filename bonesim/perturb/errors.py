"""Instrument and specimen error models.

Hardware supplies these for free; a simulation study must put them in
deliberately, and the credibility of the study rests on how honestly it does so.
Without them a ratio-based detector is scale-invariant and cannot respond to
target strength at all - there is no floor for the peak to stand above.

Two kinds, applied at different points:

  before the forward solve - errors that change the physics that is measured
    (stage position jitter, standoff variation). These must perturb the geometry
    the solver sees, while the recorded scan coordinates stay nominal, exactly
    as a real instrument does.

  after the forward solve - errors the instrument adds to an otherwise correct
    measurement (receiver noise, cable phase drift).

Repeat measurements in the experiment matrix are generated by re-drawing these,
not by re-solving: a remount changes the instrument, not the anatomy
(docs/compute-budget.md).
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from ..forward.base import ScanData


@dataclass(frozen=True)
class Instrument:
    """Error budget for one acquisition.

    dynamic_range_db  VNA noise floor below the strongest received signal. A
                      1 kHz IF bandwidth at -5 dBm output gives roughly 95 dB.
    cable_delay_rms   RMS electrical-delay drift between scan positions, as a
                      random walk. The proposal warns that flexing the cable
                      changes its phase and that it must be clamped; this is
                      the residual after clamping. 1 fs of two-way delay is
                      about 0.04 rad at 10 GHz.
    stage_jitter      RMS scan-position error, m. Proposal 2.4 requires better
                      than 0.1 mm repeatability, and explains why: 0.5 mm at
                      10 GHz is about 60 degrees of phase error, which destroys
                      the coherence migration depends on.
    standoff_sigma    RMS antenna-to-skin standoff error, m. Proposal 2.2 holds
                      this to under 0.5 mm.
    """
    dynamic_range_db: float = 95.0
    cable_delay_rms: float = 1e-15
    stage_jitter: float = 100e-6
    standoff_sigma: float = 300e-6
    seed: int = 0

    def rng(self, offset: int = 0) -> np.random.Generator:
        return np.random.default_rng(self.seed + offset)

    # --- applied before the forward solve --------------------------------

    def actual_positions(self, x_nominal: np.ndarray) -> np.ndarray:
        """Where the antenna really was, given commanded positions."""
        r = self.rng(1)
        return np.asarray(x_nominal, float) + r.normal(
            0.0, self.stage_jitter, size=np.size(x_nominal))

    def actual_standoff(self, nominal: float, n: int) -> np.ndarray:
        """Per-position standoff. Slowly varying, not independent per point.

        A real stage is not randomly re-shimmed at every step; standoff error
        comes from limb tilt and rail straightness, which vary smoothly along
        the scan. Modelled as a smoothed random walk.
        """
        r = self.rng(2)
        # A few smooth bends across the scan, not white noise: rail
        # straightness and limb tilt vary over centimetres, not millimetres.
        # This matters because smooth drift stays low-rank and the SVD stage
        # can reject it, whereas white standoff noise would be irreducible
        # clutter and would dominate any fracture response.
        t = np.linspace(0.0, 1.0, n)
        drift = sum(r.normal() * np.sin(np.pi * m * t + r.uniform(0, np.pi))
                    for m in (1, 2, 3))
        drift -= drift.mean()
        if drift.std() > 0:
            drift *= self.standoff_sigma / drift.std()
        return nominal + drift

    # --- applied after the forward solve ---------------------------------

    def add_receiver_noise(self, data: ScanData) -> ScanData:
        """Additive complex Gaussian noise at the stated dynamic range."""
        r = self.rng(3)
        ref = float(np.abs(data.s11).max())
        sigma = ref * 10.0 ** (-self.dynamic_range_db / 20.0)
        noise = (r.normal(0.0, sigma / np.sqrt(2), data.s11.shape)
                 + 1j * r.normal(0.0, sigma / np.sqrt(2), data.s11.shape))
        return data.copy_with(data.s11 + noise,
                              dynamic_range_db=self.dynamic_range_db)

    def add_cable_drift(self, data: ScanData) -> ScanData:
        """Random-walk electrical-delay drift across scan positions.

        Applied as a delay rather than a fixed phase, because a cable's phase
        error grows with frequency - that is what makes it so damaging to a
        wideband coherent sum.
        """
        r = self.rng(4)
        walk = np.cumsum(r.normal(0.0, self.cable_delay_rms, data.n_scan))
        walk -= walk.mean()
        ramp = np.exp(-2j * np.pi * np.outer(data.f, 2.0 * walk))
        return data.copy_with(data.s11 * ramp,
                              cable_delay_rms=self.cable_delay_rms)

    def apply_post(self, data: ScanData) -> ScanData:
        return self.add_cable_drift(self.add_receiver_noise(data))


@dataclass(frozen=True)
class SpecimenVariation:
    """Between-specimen biological variation (proposal 4.1 covariates).

    Every specimen is a different animal: different cortical wall thickness,
    different overlay, different tissue hydration. Without this the matrix has
    eight identical bones and the leave-one-specimen-out cross-validation of
    section 5 is meaningless, because there is nothing to leave out.
    """
    cortex_cv: float = 0.15         # coefficient of variation on wall thickness
    overlay_cv: float = 0.20
    eps_cv: float = 0.10            # tissue permittivity scatter
    seed: int = 0

    def draw(self, phantom, specimen: int):
        r = np.random.default_rng(self.seed * 1000 + specimen)
        cortex = phantom.cortex * (1 + r.normal(0, self.cortex_cv))
        overlay = phantom.overlay * (1 + r.normal(0, self.overlay_cv))
        p = phantom.with_overlay(max(overlay, phantom.skin * 1.2))
        return type(p)(**{**p.__dict__, "cortex": max(cortex, 5e-4)})
