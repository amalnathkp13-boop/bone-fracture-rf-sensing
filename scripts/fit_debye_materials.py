"""Stage 1 deliverable: fit Debye models to every tissue and emit gprMax cards.

Sweeps pole count to show the accuracy/cost trade-off, then writes the material
cards used by every subsequent FDTD model. Each extra pole costs memory and
time in the solver, so the smallest pole count meeting the error target wins.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np

from bonesim.materials import tissues as T
from bonesim.materials.debye import fit_debye

F_LO, F_HI = 3e9, 11e9          # proposal section 2.2 sweep
DT = 4.716e-13                  # 2D Courant limit at 0.2 mm (docs/compute-budget)
# 0.5%, not the 2% that one pole would satisfy. A single pole leaves cortical
# bone at 1.9% error, and cortical bone is the target material: that error is a
# systematic bias on the very scatterer being imaged, not random noise it can be
# averaged against. A second pole costs one auxiliary field array per material
# and buys an 8x reduction, which is the right trade.
TARGET = 0.005

MATERIALS = ["skin_dry", "fat", "muscle", "cortical_bone",
             "cortical_bone_wet", "marrow", "blood"]


def main() -> int:
    print(f"Fitting Debye models over {F_LO/1e9:g}-{F_HI/1e9:g} GHz")
    print(f"time step {DT*1e15:.1f} fs; all tau must exceed it\n")

    print(f"{'material':<20}{'poles':>6}{'max err eps':>13}{'max err sigma':>15}")
    print("-" * 54)
    chosen: dict[str, object] = {}
    for name in MATERIALS:
        mat = T.get(name)
        for n in (1, 2, 3, 4):
            fit = fit_debye(mat, F_LO, F_HI, n_poles=n, tau_min=2 * DT)
            worst = max(fit.max_err_eps, fit.max_err_sigma)
            mark = ""
            if name not in chosen and worst < TARGET:
                chosen[name] = fit
                mark = "   <- selected"
            print(f"{name if n == 1 else '':<20}{n:>6}"
                  f"{fit.max_err_eps:>12.3%}{fit.max_err_sigma:>15.3%}{mark}")
        if name not in chosen:
            chosen[name] = fit          # 4-pole fallback
            print(f"{'':<20}{'':>6}{'':>12}{'  target not met, using 4':>15}")
        print()

    print("=" * 60)
    print("gprMax material cards")
    print("=" * 60)
    lines = [f"## Debye fits to Gabriel 4-Cole-Cole, valid {F_LO/1e9:g}-"
             f"{F_HI/1e9:g} GHz only.",
             "## Generated by scripts/fit_debye_materials.py - do not edit.",
             ""]
    for name, fit in chosen.items():
        lines.append(f"## {name}: {fit.n_poles} poles, max error "
                     f"{max(fit.max_err_eps, fit.max_err_sigma):.2%} "
                     f"[{fit.source}]")
        lines.append(fit.gprmax_cards(dt=DT))
        lines.append("")
    text = "\n".join(lines)
    print(text)

    out = Path(__file__).resolve().parent.parent / "config" / "materials.in"
    out.write_text(text)
    print(f"written -> {out}")

    worst = max(max(f.max_err_eps, f.max_err_sigma) for f in chosen.values())
    print(f"\nworst-case error across all materials: {worst:.3%}")
    if worst < TARGET:
        print("STAGE 1 DEBYE FIT PASS")
        return 0
    print("STAGE 1 DEBYE FIT FAIL")
    return 1


if __name__ == "__main__":
    sys.exit(main())
