"""Emit the three Stage 0 smoke-test scenes.

A raw monostatic trace is dominated by source self-coupling, whose pulse is far
longer than the echo delays of interest. Targets are therefore isolated by
differencing scenes, which is the same empty-scene subtraction used in the real
processing chain (proposal 2.5, step 3):

    A - B  isolates the PEC rod   (slab present in both, rod only in A)
    B - C  isolates the slab      (free space reference)

Source and receiver are co-located, which is the true monostatic S11 geometry.
"""
from pathlib import Path

# ---- geometry (metres) -------------------------------------------------
DX = 0.0005
DOM = (0.070, 0.060, DX)
TW = 2e-9

SLAB_Y0, SLAB_Y1 = 0.020, 0.045      # fat-like layer
SLAB_EPS, SLAB_SIG = 5.0, 0.6

ROD_X, ROD_Y, ROD_R = 0.035, 0.033, 0.003

ANT_X, ANT_Y = 0.035, 0.050          # 5 mm standoff above slab
F_CENTRE = 7e9

HEADER = """#title: {title}
##
## Stage 0 smoke test, scene {tag}. 2D: domain is one cell thick in z.
## Generated by scripts/gen_smoketest.py - do not edit by hand.

#domain: {dx:.4f} {dy:.4f} {dz:.4f}
#dx_dy_dz: {d:.4f} {d:.4f} {d:.4f}
#time_window: {tw:g}

#waveform: gaussiandot 1 {fc:g} pulse
#hertzian_dipole: z {ax:.4f} {ay:.4f} 0 pulse
#rx: {ax:.4f} {ay:.4f} 0
"""

SLAB = """
#material: {eps} {sig} 1 0 fatlike
#box: 0 {y0:.4f} 0 {dx:.4f} {y1:.4f} {dz:.4f} fatlike
"""

ROD = """
#cylinder: {x:.4f} {y:.4f} 0 {x:.4f} {y:.4f} {dz:.4f} {r:.4f} pec
"""

SCENES = {
    "A_rod":  {"slab": True,  "rod": True,
               "title": "slab + PEC rod"},
    "B_slab": {"slab": True,  "rod": False,
               "title": "slab only (empty-scene reference for the rod)"},
    "C_free": {"slab": False, "rod": False,
               "title": "free space (reference for the slab)"},
}


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "config"
    out.mkdir(exist_ok=True)
    for tag, s in SCENES.items():
        text = HEADER.format(title=f"bonesim smoke test - {s['title']}", tag=tag,
                             dx=DOM[0], dy=DOM[1], dz=DOM[2], d=DX, tw=TW,
                             fc=F_CENTRE, ax=ANT_X, ay=ANT_Y)
        if s["slab"]:
            text += SLAB.format(eps=SLAB_EPS, sig=SLAB_SIG, y0=SLAB_Y0,
                                y1=SLAB_Y1, dx=DOM[0], dz=DOM[2])
        if s["rod"]:
            text += ROD.format(x=ROD_X, y=ROD_Y, r=ROD_R, dz=DOM[2])
        path = out / f"smoketest_{tag}.in"
        path.write_text(text)
        print(f"wrote {path.name}  ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
